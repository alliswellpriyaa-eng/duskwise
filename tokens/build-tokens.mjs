// Generates src/css/tokens.css and src/engine/palettes.ts from tokens.mjs.
// Run: node tokens/build-tokens.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildPrimitives, MOODS, STATIC, COLORS, PRESETS } from "./tokens.mjs";
import { css } from "./color.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const outCss = resolve(here, "../src/css/tokens.css");
const outTs = resolve(here, "../src/engine/palettes.ts");

const primitives = buildPrimitives();
const indent = (lines, n = 4) => lines.map((l) => " ".repeat(n) + l).join("\n");

/**
 * Theme-color roles as CSS. The chosen color (--dw-p-* / --dw-h-*, set by
 * data-dw-primary / data-dw-highlight) falls back to the mood's own default.
 * These lines sit in every mood block so nested moods re-light the colors.
 */
function themeColorLines(prefix, slot) {
  const h = `--_${slot}h`, c = `--_${slot}c`, b = `--_${slot}b`;
  return [
    `${h}: var(--dw-${slot}-h, var(--dw-mood-${slot}-h));`,
    `${c}: var(--dw-${slot}-c, var(--dw-mood-${slot}-c));`,
    `${b}: var(--dw-${slot}-b, var(--dw-mood-${slot}-b));`,
    `--dw-${prefix}: oklch(calc(var(--dw-l-fill) + var(${b}) * var(--dw-l-fill-up)) var(${c}) var(${h}));`,
    `--dw-on-${prefix}: oklch(calc(var(--dw-l-on) + var(${b}) * var(--dw-l-on-up)) 0.02 var(${h}));`,
    `--dw-${prefix}-ink: oklch(var(--dw-l-ink) calc(var(${c}) * var(--dw-c-ink)) var(${h}));`,
    `--dw-${prefix}-soft: oklch(var(--dw-l-soft) calc(var(${c}) * var(--dw-c-soft)) var(${h}));`,
  ];
}

function moodLines(mood) {
  const { colors, other, light, primary, highlight } = MOODS[mood];
  const r = (n) => Number(n.toFixed(3));
  const lines = Object.entries(colors).map(([role, prim]) => `--dw-${role}: var(--dw-${prim});`);
  lines.push(
    `--dw-l-fill: ${light.fill}; --dw-l-fill-up: ${r(light.fillBright - light.fill)};`,
    `--dw-l-on: ${light.on}; --dw-l-on-up: ${r(light.onBright - light.on)};`,
    `--dw-l-ink: ${light.ink}; --dw-c-ink: ${light.inkC}; --dw-l-soft: ${light.soft}; --dw-c-soft: ${light.softC};`,
    `--dw-mood-p-h: ${primary[0]}; --dw-mood-p-c: ${primary[1]}; --dw-mood-p-b: ${primary[2]};`,
    `--dw-mood-h-h: ${highlight[0]}; --dw-mood-h-c: ${highlight[1]}; --dw-mood-h-b: ${highlight[2]};`,
    ...themeColorLines("accent", "p"),
    ...themeColorLines("highlight", "h")
  );
  for (const [k, v] of Object.entries(other)) lines.push(`--dw-${k}: ${v};`);
  lines.push(`color-scheme: ${mood === "night" ? "dark" : "light"};`);
  return lines;
}

const primitiveLines = Object.entries(primitives).map(([name, v]) => `--dw-${name}: ${css(v)};`);
const staticLines = Object.entries(STATIC).map(([k, v]) => `--dw-${k}: ${v};`);

const blocks = [];
blocks.push(`/* Generated by tokens/build-tokens.mjs - do not edit by hand. */`);
blocks.push(`@layer dw.tokens {`);
blocks.push(`  /* Tier 1: primitives + static tokens, plus the default (day) mood */`);
blocks.push(`  :root {\n${indent(primitiveLines)}\n\n${indent(staticLines)}\n\n${indent(moodLines("day"))}\n  }`);

for (const mood of Object.keys(MOODS)) {
  blocks.push(`  /* Tier 2: ${mood} mood */\n  [data-dw-mood="${mood}"] {\n${indent(moodLines(mood))}\n  }`);
}

blocks.push(
  `  /* No JavaScript? Follow the operating system's dark mode. */\n` +
    `  @media (prefers-color-scheme: dark) {\n    :root:not([data-dw-mood]) {\n${indent(moodLines("night"), 6)}\n    }\n  }`
);

const colorRules = [];
for (const [name, [h, c, b]] of Object.entries(COLORS)) {
  colorRules.push(`  [data-dw-primary="${name}"] { --dw-p-h: ${h}; --dw-p-c: ${c}; --dw-p-b: ${b}; }`);
  colorRules.push(`  [data-dw-highlight="${name}"] { --dw-h-h: ${h}; --dw-h-c: ${c}; --dw-h-b: ${b}; }`);
}
blocks.push(
  `  /* Theme colors: pick any two of ${Object.keys(COLORS).length}.\n` +
    `     <html data-dw-primary="pistachio" data-dw-highlight="pink">\n` +
    `     Each mood re-lights them, so every pair stays readable day and night. */\n` +
    colorRules.join("\n")
);

blocks.push(
  `  /* Users who ask for more contrast get it in every mood. */\n` +
    `  @media (prefers-contrast: more) {\n    :root, [data-dw-mood] {\n` +
    `      --dw-muted: var(--dw-text);\n      --dw-border: var(--dw-border-strong);\n      --dw-warmth: 0 !important;\n    }\n  }`
);
blocks.push(`}`);

mkdirSync(dirname(outCss), { recursive: true });
writeFileSync(outCss, blocks.join("\n\n") + "\n");

const ts =
  `// Generated by tokens/build-tokens.mjs - do not edit by hand.\n\n` +
  `export const COLOR_NAMES = ${JSON.stringify(Object.keys(COLORS))} as const;\n\n` +
  `export type ColorName = (typeof COLOR_NAMES)[number];\n\n` +
  `export const PRESETS: Record<string, readonly [ColorName, ColorName]> = ${JSON.stringify(PRESETS, null, 2)} as const;\n`;
writeFileSync(outTs, ts);

const n = Object.keys(COLORS).length;
console.log(
  `tokens.css written: ${Object.keys(primitives).length} primitives, ${Object.keys(MOODS).length} moods, ` +
    `${n} theme colors (${n * (n - 1)} pairs), ${Object.keys(PRESETS).length} presets`
);
